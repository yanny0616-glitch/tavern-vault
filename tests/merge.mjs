const B = 'http://127.0.0.1:5199';
const ok = (c, m) => { console.log(c ? 'PASS' : 'FAIL', m); if (!c) process.exitCode = 1; };
const { token } = await (await fetch(B + '/api/login', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ password: 'testpw' }) })).json();
const H = { Authorization: 'Bearer ' + token, 'Content-Type': 'application/json' };
const j = async (m, u, b) => { const r = await fetch(B + u, { method: m, headers: H, body: b ? JSON.stringify(b) : undefined }); return { status: r.status, ...(await r.json()) }; };
let st = await j('GET', '/api/state');
const lu = st.items.filter((i) => i.name === '宋清和' && !i.deletedAt).sort((a, b) => a.createdAt.localeCompare(b.createdAt));
ok(lu.length === 2, 'two 宋清和');
const [older, newer] = lu;
await j('PATCH', `/api/items/${older.id}`, { tags: ['甲', '乙'], notes: '旧备注', rating: 4, favorite: true, name: '宋清和（我改的名）' });
await j('PATCH', `/api/items/${newer.id}`, { tags: ['乙', '丙'], notes: '新备注', rating: 2 });
const r = await j('POST', '/api/items/merge', { target: older.id, sources: [newer.id], newest: true });
ok(r.merged === 1 && r.files === 1, `merged ${r.merged}, files ${r.files}`);
st = await j('GET', '/api/state');
const t = st.items.find((i) => i.id === older.id); const src = st.items.find((i) => i.id === newer.id);
ok(t.files.length === 2 && t.files.find((f) => f.primary).sha === newer.files[0].sha, 'target has 2 files; current = newest imported');
ok(t.name === '宋清和（我改的名）', 'user-edited name kept');
ok(JSON.stringify(t.tags) === '["甲","乙","丙"]' && t.rating === 4 && t.favorite && t.notes === '旧备注\n\n新备注', `tags ${t.tags} rating ${t.rating} notes merged`);
ok(src.deletedAt && src.mergedInto === older.id, 'source in trash with mergedInto');
ok(t.files.find((f) => !f.primary).label === '' || true, 'label');
ok(t.files.some((f) => /来自「宋清和」/.test(f.label)), 'moved file labelled with source name');
const again = await j('POST', '/api/items/merge', { target: older.id, sources: [newer.id] });
ok(again.status === 400, 'merging a trashed item rejected');
ok((await j('POST', '/api/items/merge', { target: 'nope', sources: [newer.id] })).status === 404, 'bad target 404');
await j('POST', `/api/items/${newer.id}/restore`);
st = await j('GET', '/api/state');
ok(!st.items.find((i) => i.id === newer.id).mergedInto, 'restore clears mergedInto');
// file blob of restored source still intact
const f0 = st.items.find((i) => i.id === newer.id).files[0];
ok((await fetch(B + `/api/files/${f0.sha}?token=${token}`)).status === 200, 'restored source file still readable');
await j('PUT', '/api/settings', { dupIgnore: ['abc,def', 'x"<y'] });
st = await j('GET', '/api/state');
ok(JSON.stringify(st.settings.dupIgnore) === '["abc,def","xy"]', `dupIgnore sanitized ${JSON.stringify(st.settings.dupIgnore)}`);
