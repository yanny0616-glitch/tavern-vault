  const first = p.locator('.ai-card.is-done').first();
  const name = (await first.locator('.row-title').innerText()).trim();
  await first.locator('.ai-tag.on').last().click();
  const before = (await (await fetch(B + '/api/state')).json()).items.find((i) => i.name === name);
  await first.locator('textarea').fill('手动改过的简介');
  ok(await first.locator('.ai-sec-head select').nth(1).inputValue() === 'ai', 'summary defaults to 存为 AI 简介');
