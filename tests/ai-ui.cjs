  await p.fill('.sheet input[placeholder^="例如"]', '模拟 Claude');
  await p.fill('.sheet input[placeholder="https://api.anthropic.com/v1"]', 'http://127.0.0.1:5197');
  await p.fill('.sheet input[type=password]', 'sk-test-1234');
  await p.click('.sheet button:has-text("拉取列表")');
  // 模型选择面板：全部模型、按厂商分组、搜索
  await p.waitForSelector('.sheet:has-text("选择模型") .model-opt');
  ok(await p.locator('.model-opt').count() === 18 && /共 18 个/.test(await p.textContent('.model-search')), 'model picker lists all 18 models');
  ok((await p.locator('.model-group-head').allTextContents()).some((t) => t.startsWith('openai')), 'models grouped by vendor');
  await p.screenshot({ path: `${OUT}/0-models.png` });
  await p.fill('.model-search input', 'qwen');
  ok(await p.locator('.model-opt').count() === 3, 'search filters models');
  await p.fill('.model-search input', 'mock large');
  ok(await p.locator('.model-opt').count() === 1, 'multi-word search');
  await p.click('.model-opt');
  ok(await p.inputValue('.sheet input[placeholder^="模型名"]') === 'mock-large', 'picked model filled in');
  await p.click('.sheet button:has-text("选择模型")');
  await p.waitForSelector('.model-opt.on');
  ok(await p.textContent('.model-opt.on') === 'mock-large' && await p.locator('.model-opt').count() === 18, 'reopen without refetch, current model marked');
  await p.keyboard.press('Escape'); await p.waitForTimeout(300);
  await p.click('.sheet-foot button:has-text("测试连接")');
  await p.waitForSelector('.sheet >> text=连接成功');
  await p.screenshot({ path: `${OUT}/1-profile.png` });
  await p.click('.sheet-foot button:has-text("保存")');
  await p.waitForSelector('.ai-profile.active');
  await p.waitForTimeout(500);
  await p.click('.ai-rules summary');
  await p.waitForTimeout(300);
  await p.evaluate(() => document.querySelector('.ai-profile').scrollIntoView({ block: 'start' }));
  await p.screenshot({ path: `${OUT}/2-settings.png` });
  ok(true, 'profile saved via UI');
  // 仓库多选 → AI 整理
  await p.goto(B + '/#/library'); await p.waitForSelector('.card');
  await p.click('button[title="多选"]');
  const cards = p.locator('.card'); for (let i = 0; i < 3; i++) await cards.nth(i).click();
  await p.click('.sel-act:has-text("AI 整理")');
  await p.waitForSelector('.sheet.choice');
  await p.screenshot({ path: `${OUT}/3-confirm.png` });
  await p.click('.sheet.choice button:has-text("看看发送内容")');
  await p.waitForSelector('pre.code');
  await p.screenshot({ path: `${OUT}/4-preview.png` });
  await p.keyboard.press('Escape');
  await p.waitForSelector('.sheet.choice');
  await p.click('.sheet.choice button:has-text("开始整理")');
