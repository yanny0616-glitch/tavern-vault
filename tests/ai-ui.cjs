  await p.waitForTimeout(400);
  await p.screenshot({ path: `${OUT}/5-running.png` });
  await p.waitForSelector('.ai-card.is-done', { timeout: 15000 });
  await p.waitForFunction(() => !document.querySelector('.ai-card.is-running, .ai-card.is-queued'), null, { timeout: 15000 });
