  await p.click('.ai-chip');
  await p.waitForSelector('.ai-card.is-done');
  ok(await p.locator('.ai-card.is-done').first().locator('textarea').inputValue() === '手动改过的简介', 'edits kept after closing review');
  await p.locator('.ai-card.is-done').first().locator('button:has-text("写入")').click();
  await p.waitForFunction((nn) => document.querySelectorAll('.ai-card.is-done').length === nn - 1, n);
  const st = await (await fetch(B + '/api/state')).json();
  const it = st.items.find((i) => i.name === name);
  ok(it.ai?.summary === '手动改过的简介' && it.description === before.description && it.ai?.at, `applied to ${name}: ai.summary=${it.ai?.summary} desc unchanged=${it.description === before.description} tags=${it.tags}`);
  await p.click('.ai-head button:has-text("全部写入")').catch(() => p.locator('.ai-card.is-done button:has-text("写入")').first().click());
  await p.waitForSelector('text=没有待审核的结果', { timeout: 8000 });
  ok(true, 'all applied');
  await p.keyboard.press('Escape');
  ok(await p.locator('.ai-chip').isHidden(), 'chip hidden after review');
  // 详情：AI 记录 + 对比解读
  await p.click('.topbar button:has-text("完成")');
  ok(await p.locator('.card .card-ai').count() >= 1, `library cards show AI summary (${await p.locator('.card .card-ai').count()})`);
  await p.screenshot({ path: `${OUT}/6b-library.png` });
  await p.click('.card:has-text("紫夜")');
